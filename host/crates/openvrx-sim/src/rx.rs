//! One receiver: radio path, C5 analog front end and ADC, the PARLIO
//! sample clock against the MODEM_DIAG bus, and the FX2 lanes.
//!
//! Per bus sample `m` (the receiver's own 80 MHz clock) the receiver sees
//! the transmitter at position `p(m) = p0 + r m + q m^2` (clock ratio and
//! drift), so line periods measured in samples carry the crystal error.
//! The bus value is
//!
//! ```text
//! z = a1(t) e^{j 2pi (phi(p) + lo(m))} + a2(t) e^{j 2pi (phi(p - d) + lo(m))} + n
//! ```
//!
//! through the C5's 5th-order Butterworth channel filter, then scaled by
//! the gain index, offset by the gain-dependent I DC, quantised to 10 bits
//! with clipping (low bits dead). `a1`, `a2` carry C/N, scenario, antenna
//! pattern, fading and retune muting; `lo` the LO error, tuning and drift;
//! `n` white Gaussian noise of fixed density (C/N per 20 MHz channel, as in
//! C5VRX sim.py: noise power in the normal filter).
//!
//! Sampling: sample clock edges sit at PLL tick positions `x_k` (240 MHz
//! ticks, 3 per bus sample), advancing by the divider (by divider + 1
//! during a slip). Each FX2 lane latches the bus value that is current at
//! `x_k` minus its own skew minus clock jitter, so an edge near a bus
//! transition mixes old and new bits lane by lane (the sampling-phase
//! lottery); clean positions read every lane from the same bus sample.

use crate::channel::{Antenna, FadingProcess};
use crate::config::{Action, Agc, ChannelFilter, Lottery, RxConfig, Scenario, SimConfig};
use crate::dsp::{mix_seed, splitmix, unit_from, Cascade, ComplexIir};
use crate::tx::{TxBlock, Transmitter, BUS_HZ};
use openvrx_core::lanes::LaneEncoding;
use openvrx_core::{LaneFormat, SampleFormat};
use rand::{Rng, RngCore, SeedableRng};
use rand_distr::StandardNormal;

/// Bus samples of IIR warm-up before a work unit.
pub const WARM: u64 = 256;
/// Bus samples between envelope (fading, C/N) evaluation points.
const ENV_STEP: u64 = 256;
/// Noise generator chunk (independent seeded stream per chunk).
const NOISE_CHUNK: u64 = 256;
/// Retune settling time (carrier muted).
const RETUNE_SETTLE_S: f64 = 100e-6;

#[derive(Clone, Debug)]
struct LoSeg {
    m0: u64,
    phase0: f64,
    /// Baseband rotation rate (Hz) at m0 and its slope (Hz/s).
    f0: f64,
    fdot: f64,
    /// Carrier inside the representable band.
    present: bool,
    mhz: u32,
    offset_khz: i32,
}

/// Something that happens at a bus sample.
#[derive(Clone, Debug, PartialEq)]
pub struct Effect {
    pub m: u64,
    pub action: Action,
    /// Generated by the gain loop (not scheduled).
    pub from_agc: bool,
}

/// Realised random parameters of a receiver (stored in the sidecar).
#[derive(Clone, Debug, serde::Serialize)]
pub struct Realised {
    pub rx: u8,
    pub crystal_ppm: f64,
    pub lo_offset_hz: f64,
    pub clock_ratio: f64,
    pub start_delay_us: f64,
    pub phase_ticks: f64,
    pub lottery_mixed: bool,
    pub lane_skew_ticks: Vec<f64>,
    pub initial_gain: u32,
    pub multipath_phase_deg: Option<f64>,
}

pub struct Receiver {
    pub idx: u8,
    pub cfg: RxConfig,
    pub format: SampleFormat,
    seed: u64,
    // Clock mapping.
    pub p0: f64,
    pub r: f64,
    q: f64,
    // Front end.
    filt: Cascade,
    /// Noise power of this filter relative to the normal filter.
    noise_ratio: f64,
    noise_std: f32,
    lo_offset_hz: f64,
    lo_drift_hz_per_s: f64,
    channel_hz: f64,
    sigma_n: f64,
    cn_db: f64,
    scenario: Scenario,
    antenna: Antenna,
    fade1: FadingProcess,
    fade2: Option<(FadingProcess, f64, f64, f64)>, // process, delay (tx samples), share, phase (cycles)
    share1: f64,
    lo: Vec<LoSeg>,
    mutes: Vec<(u64, u64)>,
    gains: Vec<(u64, u32)>,
    gain_lin: Vec<f32>,
    dc_i: Vec<f32>,
    dc_q: f32,
    q_step: i32,
    // Lanes.
    lut_i: Vec<u32>,
    lut_q: Vec<u32>,
    angle: bool,
    lane_bits: Vec<u32>,
    skews: Vec<f32>,
    jitter: f32,
    skew_max: f32,
    // Sampling state.
    edge_x: f64,
    pub edge_count: u64,
    divider: u32,
    slip_left: u32,
    pub effects: Vec<Effect>,
    next_effect: usize,
    // Progress.
    pub m_next: u64,
    pub m_total: u64,
    // Gain loop.
    agc_next_t: f64,
    agc_pending: Option<u64>,
    pub realised: Realised,
}

fn dc_table(table: &[(f64, f64)], gain: f64) -> f64 {
    match table {
        [] => 0.0,
        [p] => p.1,
        _ => {
            let k = table
                .windows(2)
                .position(|w| gain <= w[1].0)
                .unwrap_or(table.len() - 2);
            let (a, b) = (table[k], table[k + 1]);
            a.1 + (b.1 - a.1) * (gain - a.0) / (b.0 - a.0).max(1e-9)
        }
    }
}

impl Receiver {
    /// Builds receiver `idx`. `start_tx` is the transmitter position of
    /// rx0's first bus sample.
    pub fn new(cfg: &SimConfig, idx: usize, start_tx: f64) -> Receiver {
        let rc = cfg.receivers[idx].clone();
        let seed = mix_seed(&[cfg.seed, 0x5258, idx as u64]);
        let mut hs = seed;
        let mut uni = || {
            hs = splitmix(hs);
            unit_from(hs)
        };
        let crystal_ppm = rc.crystal_ppm.unwrap_or_else(|| (uni() * 2.0 - 1.0) * 15.0);
        let start_delay_us = if idx == 0 {
            0.0
        } else {
            rc.start_delay_us.unwrap_or_else(|| uni() * 500.0)
        };
        let eps_rx = crystal_ppm * 1e-6;
        let eps_cam = cfg.vtx.video_clock_ppm * 1e-6;
        let r = (1.0 + eps_cam) / (1.0 + eps_rx);
        let q = -r * rc.ppm_drift_per_s * 1e-6 / BUS_HZ * 0.5;
        // The stream starts start_delay later (in true time), i.e. at a
        // later transmitter position.
        let p0 = start_tx + start_delay_us * 1e-6 * BUS_HZ * (1.0 + eps_cam);

        let filt = Cascade::butterworth_lowpass(5, rc.filter.cutoff_hz() / BUS_HZ);
        let normal = Cascade::butterworth_lowpass(5, ChannelFilter::Normal.cutoff_hz() / BUS_HZ);
        // Per-component input std so the normal filter passes sigma_n^2.
        let sigma_n = rc.noise_floor_rms;
        let noise_std = (sigma_n / (2.0 * normal.noise_gain()).sqrt()) as f32;

        let ch_hz = cfg.vtx.channel_mhz as f64 * 1e6;
        let lo_offset_hz = rc.lo_offset_hz.unwrap_or(eps_rx * ch_hz);
        let lo_drift = rc.ppm_drift_per_s * 1e-6 * ch_hz;
        let lo = vec![LoSeg {
            m0: 0,
            phase0: 0.0,
            f0: -lo_offset_hz,
            fdot: -lo_drift,
            present: true,
            mhz: cfg.vtx.channel_mhz,
            offset_khz: 0,
        }];

        let fade1 = FadingProcess::new(&cfg.channel.fading, mix_seed(&[seed, 1]));
        let mut mp_phase = None;
        let (share1, fade2) = match &cfg.channel.multipath {
            Some(mp) => {
                let m2 = 10f64.powf(mp.rel_db / 10.0);
                let ph = mp.phase_deg.unwrap_or_else(|| uni() * 360.0);
                mp_phase = Some(ph);
                let proc = if mp.fading {
                    FadingProcess::new(&cfg.channel.fading, mix_seed(&[seed, 2]))
                } else {
                    FadingProcess::new(&crate::config::Fading::default(), 0)
                };
                (
                    (1.0 / (1.0 + m2)).sqrt(),
                    Some((proc, mp.delay_ns * 1e-9 * BUS_HZ, (m2 / (1.0 + m2)).sqrt(), ph / 360.0)),
                )
            }
            None => (1.0, None),
        };

        let format = SampleFormat::from_preset(rc.preset, rc.divider);
        let lanes = &format.lanes;
        let (lut_i, lut_q, angle) = match &lanes.encoding {
            LaneEncoding::Iq { i, q } => (
                (-512..512).map(|v| i.encode(v)).collect(),
                (-512..512).map(|v| q.encode(v)).collect(),
                false,
            ),
            LaneEncoding::Angle { .. } => (Vec::new(), Vec::new(), true),
        };
        let mask = lanes.used_word_mask();
        let lane_bits: Vec<u32> = (0..16).filter(|b| mask & (1 << b) != 0).collect();
        let mut nrng = rand::rngs::SmallRng::seed_from_u64(mix_seed(&[seed, 3]));
        let skews: Vec<f32> = lane_bits
            .iter()
            .map(|_| {
                let g: f64 = nrng.sample(StandardNormal);
                (g * rc.sampling.lane_skew_ticks).clamp(-0.45, 0.45) as f32
            })
            .collect();
        let skew_max = skews.iter().fold(0.0f32, |a, &s| a.max(s.abs()));
        let (phase_ticks, mixed) = match rc.sampling.lottery {
            Lottery::Clean => (0.8 + 1.4 * uni(), false),
            Lottery::Mixed => (0.4 * uni() - 0.2, true),
            Lottery::Random { p_mixed } => {
                if uni() < p_mixed {
                    (0.4 * uni() - 0.2, true)
                } else {
                    (0.8 + 1.4 * uni(), false)
                }
            }
        };

        let q_step = 1i32 << (10 - rc.adc_live_bits);
        let gmax = rc.gain_max.max(rc.gain_min) as usize;
        let gain_lin = (0..=gmax.max(127))
            .map(|g| 10f64.powf((g as f64 - rc.gain_ref as f64) * rc.gain_step_db / 20.0) as f32)
            .collect();
        let dc_i = (0..=gmax.max(127))
            .map(|g| (4.0 * rc.dc_scale * dc_table(&rc.dc_i_table, g as f64)) as f32)
            .collect();

        let antenna = Antenna::new(&rc.antenna, mix_seed(&[seed, 4]));
        let m_total = (cfg.seconds * BUS_HZ).ceil() as u64;
        let mut rx = Receiver {
            idx: idx as u8,
            format,
            seed,
            p0,
            r,
            q,
            noise_ratio: filt.noise_gain() / normal.noise_gain(),
            filt,
            noise_std,
            lo_offset_hz,
            lo_drift_hz_per_s: lo_drift,
            channel_hz: ch_hz,
            sigma_n,
            cn_db: cfg.channel.cn_db + rc.cn_offset_db,
            scenario: cfg.channel.scenario.clone(),
            antenna,
            fade1,
            fade2,
            share1,
            lo,
            mutes: Vec::new(),
            gains: Vec::new(),
            gain_lin,
            dc_i,
            dc_q: rc.dc_q as f32,
            q_step,
            lut_i,
            lut_q,
            angle,
            lane_bits,
            skews: skews.clone(),
            jitter: rc.sampling.jitter_ticks as f32,
            skew_max,
            edge_x: 6.0 + phase_ticks,
            edge_count: 0,
            divider: rc.divider,
            slip_left: 0,
            effects: Vec::new(),
            next_effect: 0,
            m_next: 0,
            m_total,
            agc_next_t: 0.0,
            agc_pending: None,
            realised: Realised {
                rx: idx as u8,
                crystal_ppm,
                lo_offset_hz,
                clock_ratio: r,
                start_delay_us,
                phase_ticks,
                lottery_mixed: mixed,
                lane_skew_ticks: skews.iter().map(|&s| s as f64).collect(),
                initial_gain: 0,
                multipath_phase_deg: mp_phase,
            },
            cfg: rc,
        };
        // Initial gain.
        let g0 = match rx.cfg.agc {
            Agc::Fixed { gain } => gain,
            Agc::Loop { initial: Some(g), .. } => g,
            Agc::Loop { target_rms, .. } => {
                let rms = rx.model_power(0.0, rx.cfg.gain_ref).sqrt();
                let steps = (20.0 * (target_rms / rms).log10() / rx.cfg.gain_step_db).round();
                (rx.cfg.gain_ref as f64 + steps) as u32
            }
        }
        .clamp(rx.cfg.gain_min, rx.cfg.gain_max);
        rx.gains.push((0, g0));
        rx.realised.initial_gain = g0;
        if let Agc::Loop { period_s, .. } = rx.cfg.agc {
            rx.agc_next_t = period_s;
        }
        // Scheduled events for this receiver.
        let mut evs: Vec<&crate::config::ScheduledEvent> = cfg
            .events
            .iter()
            .filter(|e| e.rx.is_none_or(|r| r as usize == idx))
            .filter(|e| !matches!(e.action, Action::Marker { .. }))
            .collect();
        evs.sort_by(|a, b| a.t_s.total_cmp(&b.t_s));
        for e in evs {
            let m = (e.t_s.max(0.0) * BUS_HZ) as u64;
            rx.schedule(m, e.action.clone(), false);
        }
        rx
    }

    /// Transmitter position of bus sample `m`.
    #[inline(always)]
    pub fn p_of(&self, m: f64) -> f64 {
        self.p0 + self.r * m + self.q * m * m
    }

    /// First bus sample at or after transmitter position `p`.
    pub fn m_of(&self, p: f64) -> u64 {
        let mut m = ((p - self.p0) / self.r).max(0.0);
        for _ in 0..4 {
            let f = self.p_of(m) - p;
            let d = self.r + 2.0 * self.q * m;
            m -= f / d;
        }
        let mut k = m.max(0.0).floor() as u64;
        while k > 0 && self.p_of((k - 1) as f64) >= p {
            k -= 1;
        }
        while self.p_of(k as f64) < p {
            k += 1;
        }
        k
    }

    /// Byte rate of the receiver's stream at the configured divider.
    pub fn byte_rate(&self) -> f64 {
        self.format.byte_rate()
    }

    pub fn word_bytes(&self) -> u64 {
        self.format.lanes.word_bytes as u64
    }

    /// Carrier amplitude (10-bit units at the reference gain) at time t,
    /// before fading.
    fn carrier_amp(&self, t: f64) -> f64 {
        let db = self.cn_db + self.scenario.offset_db(t) + self.antenna.gain_db(t);
        self.sigma_n * 10f64.powf(db / 20.0)
    }

    /// Expected I/Q power (signal + noise, DC excluded) at time t and gain.
    pub fn model_power(&self, t: f64, gain: u32) -> f64 {
        let a = self.carrier_amp(t);
        let (r1, i1) = self.fade1.gain(t);
        let mut s = self.share1 * self.share1 * (r1 * r1 + i1 * i1);
        if let Some((f2, _, share2, _)) = &self.fade2 {
            let (r2, i2) = f2.gain(t);
            s += share2 * share2 * (r2 * r2 + i2 * i2);
        }
        let g = self.gain_lin[gain as usize] as f64;
        let noise = self.sigma_n * self.sigma_n * self.noise_ratio;
        (a * a * s + noise) * g * g
    }

    /// Gain index in force at bus sample m.
    pub fn gain_at(&self, m: u64) -> u32 {
        let k = self.gains.partition_point(|g| g.0 <= m);
        self.gains[k.max(1) - 1].1
    }

    /// Adds an effect at bus sample m.
    pub fn schedule(&mut self, m: u64, action: Action, from_agc: bool) {
        match &action {
            Action::Gain { index } => {
                let g = (*index).clamp(self.cfg.gain_min, self.cfg.gain_max);
                let k = self.gains.partition_point(|x| x.0 <= m);
                self.gains.insert(k, (m, g));
            }
            Action::Tune { mhz, offset_khz } => {
                let last = self.lo.last().expect("lo").clone();
                let t0 = last.m0 as f64 / BUS_HZ;
                let t = m as f64 / BUS_HZ;
                let dt = t - t0;
                let phase = last.phase0 + last.f0 * dt + 0.5 * last.fdot * dt * dt;
                let tuned = *mhz as f64 * 1e6 + *offset_khz as f64 * 1e3;
                let lo_err = self.lo_offset_hz + self.lo_drift_hz_per_s * t;
                let delta = self.channel_hz - tuned;
                self.lo.push(LoSeg {
                    m0: m,
                    phase0: phase.rem_euclid(1.0),
                    f0: delta - lo_err,
                    fdot: last.fdot,
                    present: delta.abs() < 30e6,
                    mhz: *mhz,
                    offset_khz: *offset_khz,
                });
                self.mutes.push((m, m + (RETUNE_SETTLE_S * BUS_HZ) as u64));
            }
            Action::Clk { .. } | Action::Slip { .. } | Action::Marker { .. } => {}
        }
        let k = self.effects.partition_point(|e| e.m <= m);
        self.effects.insert(k, Effect { m, action, from_agc });
    }

    /// Runs the gain loop up to bus sample `m_now`; changes are placed in
    /// the vertical interval of the next field.
    pub fn run_agc(&mut self, m_now: u64, tx: &Transmitter) {
        let Agc::Loop { target_rms, low_rms, high_rms, period_s, .. } = self.cfg.agc else {
            return;
        };
        if let Some(p) = self.agc_pending {
            if m_now > p {
                self.agc_pending = None;
            }
        }
        let t_now = m_now as f64 / BUS_HZ;
        while self.agc_next_t <= t_now {
            let te = self.agc_next_t;
            self.agc_next_t += period_s;
            if self.agc_pending.is_some() {
                continue;
            }
            let g = self.gain_at((te * BUS_HZ) as u64);
            let n = 32;
            let p: f64 = (0..n)
                .map(|k| self.model_power(te - period_s * (k as f64 + 0.5) / n as f64, g))
                .sum::<f64>()
                / n as f64;
            let rms = p.sqrt();
            if rms >= low_rms && rms <= high_rms {
                continue;
            }
            let steps = (20.0 * (target_rms / rms).log10() / self.cfg.gain_step_db).round() as i64;
            let ng = (g as i64 + steps).clamp(self.cfg.gain_min as i64, self.cfg.gain_max as i64) as u32;
            if ng == g {
                continue;
            }
            // Next field's vertical interval after now, plus 3 lines.
            let p_now = self.p_of(m_now as f64);
            let half = tx.params().lines_per_frame as f64 / 2.0;
            let mut f = (p_now / (half * tx.line_period_tx())).floor() as u64;
            while tx.field_start_tx(f) < p_now {
                f += 1;
            }
            let m_e = self.m_of(tx.field_start_tx(f) + 3.0 * tx.line_period_tx());
            self.schedule(m_e, Action::Gain { index: ng }, true);
            self.agc_pending = Some(m_e);
        }
    }

    /// Generates the sample clock edges whose bus sample lies in
    /// `[self.m_next, m_hi)`, applying clock effects. Returns the edge tick
    /// positions and the global index of the first.
    pub fn gen_edges(&mut self, m_hi: u64) -> (Vec<f64>, u64) {
        let first = self.edge_count;
        let mut edges = Vec::with_capacity(((m_hi - self.m_next) * 3 / self.divider as u64 + 4) as usize);
        loop {
            let m = (self.edge_x / 3.0) as u64;
            while self.next_effect < self.effects.len() && self.effects[self.next_effect].m <= m {
                match self.effects[self.next_effect].action {
                    Action::Clk { divider } => self.divider = divider,
                    Action::Slip { count } => self.slip_left += count,
                    _ => {}
                }
                self.next_effect += 1;
            }
            if m >= m_hi {
                break;
            }
            edges.push(self.edge_x);
            let mut step = self.divider;
            if self.slip_left > 0 {
                self.slip_left -= 1;
                step += 1;
            }
            self.edge_x += step as f64;
        }
        self.edge_count += edges.len() as u64;
        (edges, first)
    }

    #[inline]
    fn lo_phase(&self, seg: &LoSeg, m: u64) -> f64 {
        let dt = (m - seg.m0) as f64 * (1.0 / BUS_HZ);
        seg.phase0 + seg.f0 * dt + 0.5 * seg.fdot * dt * dt
    }

    fn muted(&self, m: u64) -> bool {
        self.mutes.iter().any(|&(a, b)| m >= a && m < b)
    }

    /// Complex amplitudes of both rays at bus sample m (envelope points).
    fn envelope(&self, m: u64) -> [(f32, f32); 2] {
        let t = m as f64 / BUS_HZ;
        let seg = &self.lo[self.lo.partition_point(|s| s.m0 <= m).max(1) - 1];
        if !seg.present || self.muted(m) {
            return [(0.0, 0.0); 2];
        }
        let a = self.carrier_amp(t);
        let (r1, i1) = self.fade1.gain(t);
        let s1 = a * self.share1;
        let mut out = [((s1 * r1) as f32, (s1 * i1) as f32), (0.0, 0.0)];
        if let Some((f2, _, share2, ph)) = &self.fade2 {
            let (r2, i2) = f2.gain(t);
            let (s, c) = (std::f64::consts::TAU * ph).sin_cos();
            let (rr, ii) = (r2 * c - i2 * s, r2 * s + i2 * c);
            out[1] = ((a * share2 * rr) as f32, (a * share2 * ii) as f32);
        }
        out
    }

    /// Processes bus samples `[a, b)`: returns the ADC values (I, Q) of bus
    /// samples `[a - 2, b + 2)`.
    pub fn front_end(&self, tx: &TxBlock, a: u64, b: u64) -> Vec<(i16, i16)> {
        let lo_m = a.saturating_sub(WARM + 2);
        let keep = a.saturating_sub(2);
        let end = b + 2;
        // Envelope points.
        let e0 = lo_m / ENV_STEP;
        let e1 = end / ENV_STEP + 1;
        let env: Vec<[(f32, f32); 2]> = (e0..=e1).map(|e| self.envelope(e * ENV_STEP)).collect();
        let mut iir = ComplexIir::new(&self.filt);
        let mut out = Vec::with_capacity((end - keep) as usize);
        let mut rng = rand::rngs::SmallRng::seed_from_u64(0);
        let mut seg_i = self.lo.partition_point(|s| s.m0 <= lo_m).max(1) - 1;
        let mut gain_i = self.gains.partition_point(|g| g.0 <= keep).max(1) - 1;
        let ns = self.noise_std;
        let ray2 = self.fade2.as_ref().map(|f| f.1);
        let step = self.q_step;
        for m in lo_m..end {
            if m % NOISE_CHUNK == 0 || m == lo_m {
                rng = rand::rngs::SmallRng::seed_from_u64(mix_seed(&[self.seed, 0x401, m / NOISE_CHUNK]));
                if m % NOISE_CHUNK != 0 {
                    // Skip to the position inside the chunk.
                    for _ in 0..(m % NOISE_CHUNK) * 2 {
                        rng.next_u64();
                    }
                }
            }
            while seg_i + 1 < self.lo.len() && self.lo[seg_i + 1].m0 <= m {
                seg_i += 1;
            }
            let lo_ph = self.lo_phase(&self.lo[seg_i], m);
            let p = self.p_of(m as f64);
            // Envelope interpolation.
            let ei = (m / ENV_STEP - e0) as usize;
            let fr = (m % ENV_STEP) as f32 / ENV_STEP as f32;
            let (ea, eb) = (env[ei], env[ei + 1]);
            let a1 = (ea[0].0 + (eb[0].0 - ea[0].0) * fr, ea[0].1 + (eb[0].1 - ea[0].1) * fr);
            let (s, c) = crate::dsp::sincos_turns(tx.phase_at(p) + lo_ph);
            let mut zr = a1.0 * c - a1.1 * s;
            let mut zi = a1.0 * s + a1.1 * c;
            if let Some(d) = ray2 {
                let a2 = (ea[1].0 + (eb[1].0 - ea[1].0) * fr, ea[1].1 + (eb[1].1 - ea[1].1) * fr);
                let (s2, c2) = crate::dsp::sincos_turns(tx.phase_at(p - d) + lo_ph);
                zr += a2.0 * c2 - a2.1 * s2;
                zi += a2.0 * s2 + a2.1 * c2;
            }
            let nr = crate::dsp::gauss8(rng.next_u64());
            let ni = crate::dsp::gauss8(rng.next_u64());
            let (yr, yi) = iir.step(zr + ns * nr, zi + ns * ni);
            if m >= keep {
                while gain_i + 1 < self.gains.len() && self.gains[gain_i + 1].0 <= m {
                    gain_i += 1;
                }
                let g = self.gains[gain_i].1 as usize;
                let gl = self.gain_lin[g];
                let vi = gl * yr + self.dc_i[g];
                let vq = gl * yi + self.dc_q;
                let inv = 1.0 / step as f32;
                let qi = (crate::dsp::ifloor32((vi * inv).clamp(-1e6, 1e6)) * step).clamp(-512, 512 - step);
                let qq = (crate::dsp::ifloor32((vq * inv).clamp(-1e6, 1e6)) * step).clamp(-512, 512 - step);
                out.push((qi as i16, qq as i16));
            }
        }
        out
    }

    /// Encodes one bus value into a lane word.
    #[inline]
    fn encode(&self, v: (i16, i16), gain: u32) -> u32 {
        if self.angle {
            // The C5 computes the angle after removing its DC estimate.
            let i = v.0 as i32 - self.dc_i[gain as usize].round() as i32;
            let q = v.1 as i32 - self.dc_q.round() as i32;
            self.format.lanes.encode(i, q)
        } else {
            self.lut_i[(v.0 as i32 + 512) as usize] | self.lut_q[(v.1 as i32 + 512) as usize]
        }
    }

    /// Lane words for `edges` (all with bus sample in `[a, b)`), given the
    /// ADC values of bus samples `[a - 2, b + 2)`. Edge `j` has global
    /// index `first + j` (jitter seed).
    pub fn words(&self, adc: &[(i16, i16)], a: u64, edges: &[f64], first: u64) -> Vec<u32> {
        let base = a.saturating_sub(2);
        let margin = self.skew_max + 6.0 * self.jitter;
        let mut gain_i = self.gains.partition_point(|g| g.0 <= base).max(1) - 1;
        edges
            .iter()
            .enumerate()
            .map(|(j, &x)| {
                let m = (x / 3.0) as u64;
                while gain_i + 1 < self.gains.len() && self.gains[gain_i + 1].0 <= m {
                    gain_i += 1;
                }
                let g = self.gains[gain_i].1;
                let ph = (x - 3.0 * m as f64) as f32;
                let at = |mm: u64| adc[(mm - base) as usize];
                if ph > margin && ph < 3.0 - margin {
                    return self.encode(at(m), g);
                }
                // Near a transition: each lane latches its own bus sample.
                let h = splitmix(mix_seed(&[self.seed, 0x717, first + j as u64]));
                let u1 = unit_from(h).max(1e-12);
                let u2 = unit_from(splitmix(h));
                let e = (self.jitter as f64 * (-2.0 * u1.ln()).sqrt() * (std::f64::consts::TAU * u2).cos()) as f32;
                let mut word = 0u32;
                let mut cache: [(u64, u32); 3] = [(u64::MAX, 0); 3];
                for (lane, &bit) in self.lane_bits.iter().enumerate() {
                    let pos = x - (self.skews[lane] + e).clamp(-2.9, 2.9) as f64;
                    let mm = (pos.max(0.0) / 3.0) as u64;
                    let slot = (mm + 1 - m) as usize % 3;
                    if cache[slot].0 != mm {
                        cache[slot] = (mm, self.encode(at(mm), g));
                    }
                    word |= cache[slot].1 & (1 << bit);
                }
                word
            })
            .collect()
    }

    /// Group delay of the channel filter at the receiver's blanking
    /// frequency, in bus samples.
    pub fn filter_delay_bus(&self, blank_hz: f64) -> f64 {
        let f = (blank_hz + self.lo[0].f0) / BUS_HZ;
        self.filt.group_delay(f.abs())
    }

    /// Tuning and gain at start (for the sidecar).
    pub fn initial_tuning(&self) -> (u32, i32) {
        (self.lo[0].mhz, self.lo[0].offset_khz)
    }

    pub fn lane_format(&self) -> &LaneFormat {
        &self.format.lanes
    }
}


#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::*;
    use openvrx_core::LanePreset;

    fn setup(lottery: Lottery, preset: LanePreset) -> (SimConfig, Receiver) {
        let mut cfg = SimConfig::default();
        cfg.receivers[0].preset = preset;
        cfg.receivers[0].sampling.lottery = lottery;
        let rx = Receiver::new(&cfg, 0, 10_000.0);
        (cfg, rx)
    }

    #[test]
    fn lane_luts_match_encode_for_every_preset() {
        for preset in LanePreset::ALL {
            let (_, rx) = setup(Lottery::Clean, preset);
            let f = preset.format();
            for i in (-512..512).step_by(7) {
                for q in (-512..512).step_by(13) {
                    let g = rx.gains[0].1;
                    let dc = (rx.dc_i[g as usize].round() as i32, rx.dc_q.round() as i32);
                    let want = if f.has_magnitude() {
                        f.encode(i, q)
                    } else {
                        f.encode(i - dc.0, q - dc.1)
                    };
                    assert_eq!(rx.encode((i as i16, q as i16), g), want, "{preset} {i} {q}");
                }
            }
        }
    }

    #[test]
    fn mixed_bits_only_when_enabled() {
        for (lottery, expect_mixed) in [(Lottery::Clean, false), (Lottery::Mixed, true)] {
            let (_, mut rx) = setup(lottery, LanePreset::I8Q8);
            // A bus that changes every sample with all bits flipping.
            let n = 4000u64;
            let adc: Vec<(i16, i16)> = (0..n + 4)
                .map(|k| if k % 2 == 0 { (-4, 100) } else { (0, -104) })
                .collect();
            let (edges, first) = rx.gen_edges(n);
            let words = rx.words(&adc, 2, &edges[1..edges.len() - 1], first + 1);
            let mut mixed = 0;
            for (w, &x) in words.iter().zip(&edges[1..]) {
                let m = (x / 3.0) as u64;
                let clean = rx.encode(adc[m as usize], 64);
                if *w != clean {
                    // Every bit equals the old or the new value.
                    let old = rx.encode(adc[m as usize - 1], 64);
                    let new = rx.encode(adc[m as usize + 1], 64);
                    for b in 0..16 {
                        let bit = (w >> b) & 1;
                        assert!(bit == (clean >> b) & 1 || bit == (old >> b) & 1 || bit == (new >> b) & 1);
                    }
                    mixed += 1;
                }
            }
            if expect_mixed {
                assert!(mixed > words.len() / 4, "{mixed} of {}", words.len());
            } else {
                assert_eq!(mixed, 0);
            }
        }
    }

    #[test]
    fn slip_moves_the_phase() {
        let (cfg, _) = setup(Lottery::Mixed, LanePreset::I8Q8);
        let mut rx = Receiver::new(&cfg, 0, 10_000.0);
        rx.schedule(1000, Action::Slip { count: 1 }, false);
        let (edges, _) = rx.gen_edges(3000);
        let ph = |x: f64| x.rem_euclid(3.0);
        let before = ph(edges[10]);
        let after = ph(*edges.last().unwrap());
        assert!(((after - before).rem_euclid(3.0) - 1.0).abs() < 1e-9);
        // Divider 18: 6 bus samples per edge, plus one tick at the slip.
        assert!((edges[10] - edges[9] - 18.0).abs() < 1e-12);
    }

    #[test]
    fn clock_mapping_inverts() {
        let mut cfg = SimConfig::default();
        cfg.receivers[0].crystal_ppm = Some(40.0);
        cfg.receivers[0].ppm_drift_per_s = 0.5;
        let rx = Receiver::new(&cfg, 0, 5_000.0);
        for m in [0u64, 1, 12345, 80_000_000, 3_000_000_000] {
            let p = rx.p_of(m as f64);
            assert_eq!(rx.m_of(p), m);
            assert_eq!(rx.m_of(p + 1e-3), m + 1);
        }
        assert!((rx.r - 1.0 / 1.00004).abs() < 1e-12);
        assert!((rx.realised.lo_offset_hz - 40e-6 * 5732e6).abs() < 1e-3);
    }

    #[test]
    fn dc_table_interpolates() {
        let t = vec![(64.0, 20.0), (68.0, 32.0), (77.0, 85.0)];
        assert_eq!(dc_table(&t, 64.0), 20.0);
        assert_eq!(dc_table(&t, 66.0), 26.0);
        assert!((dc_table(&t, 77.0) - 85.0).abs() < 1e-9);
        assert!((dc_table(&t, 60.0) - 8.0).abs() < 1e-9);
    }
}


